#!/usr/bin/env python3
"""UX benchmark workspace: a coverage grid of competitors x flow steps.

The grid is the point. Loose screenshots are not a benchmark; screens assigned
to steps are, because only then does a MISSING screen become visible and
askable about.

Subcommands: init, add, gap, status, sheet.
Exit codes: 0 ok, 1 usage, 2 nothing to do, 5 missing dependency.
"""

from __future__ import annotations  # PEP 604 syntax on Python 3.9

import argparse
import json
import shutil
import subprocess
import sys
from pathlib import Path

STATE = "benchmark.json"
GAP_CAUSES = ("not-in-source", "not-in-product", "unknown")


def receipt(**kwargs) -> None:
    print(json.dumps(kwargs, ensure_ascii=False, indent=2))


def slug(text: str) -> str:
    keep = [c.lower() if c.isalnum() else "-" for c in text.strip()]
    out = "".join(keep)
    while "--" in out:
        out = out.replace("--", "-")
    return out.strip("-")


def load(root: Path) -> dict | None:
    path = root / STATE
    if not path.exists():
        return None
    return json.loads(path.read_text(encoding="utf-8"))


def save(root: Path, state: dict) -> None:
    (root / STATE).write_text(
        json.dumps(state, ensure_ascii=False, indent=2), encoding="utf-8")
    write_views(root, state)


def cell(state: dict, competitor: str, step: str) -> dict | None:
    return state["screens"].get(competitor, {}).get(step)


def write_views(root: Path, state: dict) -> None:
    """Human-readable mirrors of the state. Generated — never hand-edited."""
    steps, competitors = state["steps"], state["competitors"]
    lines = [f"# {state['flow']} — coverage", "",
             "Generated by benchmark.py. Do not hand-edit.", "",
             "| step | " + " | ".join(competitors) + " |",
             "|------|" + "|".join(["------"] * len(competitors)) + "|"]
    for step in steps:
        row = []
        for competitor in competitors:
            entry = cell(state, competitor, step)
            if not entry:
                row.append("·")
            elif entry["kind"] == "screen":
                row.append(f"[✓]({entry['path']})")
            else:
                row.append({"not-in-product": "✗ n/a",
                            "not-in-source": "? sin fuente",
                            "unknown": "?"}[entry["cause"]])
        lines.append(f"| {step} | " + " | ".join(row) + " |")
    lines += ["", "Legend: ✓ captured · ✗ n/a the product has no such step ·",
              "? sin fuente the source did not show it · · not looked at yet.",
              "The last two are DIFFERENT findings and must never be merged."]
    (root / "coverage.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

    src = ["# Sources", "", "One row per competitor. `shows` records what the source actually",
           "demonstrates — a brand spot proves nothing about the product's screens.", "",
           "| competitor | source | kind | shows |", "|---|---|---|---|"]
    for competitor in competitors:
        info = state["sources"].get(competitor)
        if info:
            src.append(f"| {competitor} | `{info['id']}` | {info['kind']} | {info['shows']} |")
        else:
            src.append(f"| {competitor} | — | — | not sourced yet |")
    (root / "sources.md").write_text("\n".join(src) + "\n", encoding="utf-8")


def cmd_init(args) -> int:
    root = Path(args.dir)
    if load(root) and not args.force:
        receipt(status="error", error_type="AlreadyInitialised", dir=str(root),
                hint="A benchmark already lives here. Use `add`/`gap`, or pass --force to reset.")
        return 1
    steps = [slug(s) for s in args.steps.split(",") if s.strip()]
    competitors = [slug(c) for c in args.competitors.split(",") if c.strip()]
    if len(steps) < 2 or not competitors:
        receipt(status="error", error_type="BadSpec",
                hint="Need at least 2 steps and 1 competitor.")
        return 1
    root.mkdir(parents=True, exist_ok=True)
    (root / "screens").mkdir(exist_ok=True)
    state = {"flow": args.flow, "steps": steps, "competitors": competitors,
             "screens": {c: {} for c in competitors}, "sources": {}}
    save(root, state)
    for name, body in (
        ("mission.md", f"# Mission\n\nFlow under study: **{args.flow}**\n\n"
                       "## Why\n\n<what decision this benchmark feeds. Fill this in — without it "
                       "every later run optimises for a goal that was guessed.>\n\n"
                       "## Done looks like\n\n<when to stop adding competitors>\n"),
        ("findings.md", "# Findings\n\nOne section per step, accumulated across runs.\n"),
        ("notes.md", "# Notes\n\nAgent-private: rejected sources, gotchas, things to re-check.\n"),
    ):
        path = root / name
        if not path.exists():
            path.write_text(body, encoding="utf-8")
    receipt(status="success", action="init", dir=str(root), flow=args.flow,
            steps=steps, competitors=competitors,
            hint="Workspace created. Fill in mission.md WHY before sourcing anything.")
    return 0


def cmd_add(args) -> int:
    root = Path(args.dir)
    state = load(root)
    if state is None:
        receipt(status="error", error_type="NoWorkspace", dir=str(root),
                hint="Run `init` first.")
        return 1
    competitor, step = slug(args.competitor), slug(args.step)
    if competitor not in state["competitors"]:
        receipt(status="error", error_type="UnknownCompetitor", value=competitor,
                known=state["competitors"], hint="Add it to the spec or fix the name.")
        return 1
    if step not in state["steps"]:
        receipt(status="error", error_type="UnknownStep", value=step, known=state["steps"],
                hint="A screen with no step is not a benchmark entry. Fix the name, or widen "
                     "the flow spine deliberately.")
        return 1
    source = Path(args.file)
    if not source.exists():
        receipt(status="error", error_type="FileNotFound", file=str(source))
        return 1
    index = state["steps"].index(step)
    target_dir = root / "screens" / competitor
    target_dir.mkdir(parents=True, exist_ok=True)
    target = target_dir / f"{index:02d}-{step}{source.suffix}"
    shutil.copyfile(source, target)
    state["screens"][competitor][step] = {
        "kind": "screen", "path": str(target.relative_to(root)),
        "source": args.source, "at": args.at, "note": args.note or "",
    }
    save(root, state)
    receipt(status="success", action="add", competitor=competitor, step=step,
            path=str(target), hint="Recorded. Run `status` to see what is still open.")
    return 0


def cmd_gap(args) -> int:
    root = Path(args.dir)
    state = load(root)
    if state is None:
        receipt(status="error", error_type="NoWorkspace", hint="Run `init` first.")
        return 1
    competitor, step = slug(args.competitor), slug(args.step)
    if competitor not in state["competitors"] or step not in state["steps"]:
        receipt(status="error", error_type="UnknownCell", competitor=competitor, step=step)
        return 1
    state["screens"][competitor][step] = {
        "kind": "gap", "cause": args.cause, "note": args.note or ""}
    save(root, state)
    receipt(status="success", action="gap", competitor=competitor, step=step, cause=args.cause,
            hint="'not-in-product' is a finding about the product. 'not-in-source' is a finding "
                 "about your evidence. Never record one as the other.")
    return 0


def cmd_status(args) -> int:
    root = Path(args.dir)
    state = load(root)
    if state is None:
        receipt(status="error", error_type="NoWorkspace", hint="Run `init` first.")
        return 1
    grid, open_cells = {}, []
    captured = gaps = 0
    for competitor in state["competitors"]:
        row = {}
        for step in state["steps"]:
            entry = cell(state, competitor, step)
            if entry is None:
                row[step] = "open"
                open_cells.append({"competitor": competitor, "step": step})
            elif entry["kind"] == "screen":
                row[step] = "screen"; captured += 1
            else:
                row[step] = entry["cause"]; gaps += 1
        grid[competitor] = row
    total = len(state["steps"]) * len(state["competitors"])
    receipt(status="success", action="status", flow=state["flow"],
            steps=state["steps"], competitors=state["competitors"],
            captured=captured, gaps=gaps, open=len(open_cells), total=total,
            grid=grid, open_cells=open_cells[:20],
            unsourced=[c for c in state["competitors"] if c not in state["sources"]],
            hint="Open cells are unexamined, NOT absent features. Resolve each into a screen or "
                 "a gap with a cause before drawing conclusions.")
    return 0 if not open_cells else 2


def cmd_source(args) -> int:
    root = Path(args.dir)
    state = load(root)
    if state is None:
        receipt(status="error", error_type="NoWorkspace", hint="Run `init` first.")
        return 1
    competitor = slug(args.competitor)
    if competitor not in state["competitors"]:
        receipt(status="error", error_type="UnknownCompetitor", value=competitor)
        return 1
    state["sources"][competitor] = {"id": args.id, "kind": args.kind, "shows": args.shows}
    save(root, state)
    receipt(status="success", action="source", competitor=competitor, id=args.id, kind=args.kind)
    return 0


def cmd_sheet(args) -> int:
    root = Path(args.dir)
    state = load(root)
    if state is None:
        receipt(status="error", error_type="NoWorkspace", hint="Run `init` first.")
        return 1
    if not shutil.which("ffmpeg"):
        receipt(status="error", error_type="MissingDependency", hint="brew install ffmpeg")
        return 5
    steps = state["steps"] if args.all else [slug(args.step)]
    made, empty = [], []
    for step in steps:
        if step not in state["steps"]:
            receipt(status="error", error_type="UnknownStep", value=step, known=state["steps"])
            return 1
        paths = []
        for competitor in state["competitors"]:
            entry = cell(state, competitor, step)
            if entry and entry["kind"] == "screen":
                paths.append(root / entry["path"])
        if not paths:
            empty.append(step); continue
        out = root / f"compare-{state['steps'].index(step):02d}-{step}.png"
        command = ["ffmpeg", "-hide_banner", "-loglevel", "error"]
        for path in paths:
            command += ["-i", str(path)]
        streams = "".join(f"[{i}:v]" for i in range(len(paths)))
        command += ["-filter_complex",
                    f"{streams}concat=n={len(paths)}:v=1:a=0[c];"
                    f"[c]scale=520:-1,tile={len(paths)}x1:padding=10:color=white[out]",
                    "-map", "[out]", "-frames:v", "1", "-y", str(out)]
        result = subprocess.run(command, capture_output=True, text=True, timeout=180)
        if result.returncode == 0 and out.exists():
            made.append({"step": step, "path": str(out), "competitors": len(paths)})
        else:
            empty.append(step)
    if not made:
        receipt(status="empty", steps_without_screens=empty,
                hint="Nothing to compare yet. Capture screens for at least one competitor.")
        return 2
    receipt(status="success", action="sheet", sheets=made, steps_without_screens=empty,
            hint="Each sheet places competitors side by side, left to right in spec order. "
                 "Open the sheet, not the individual screens.")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description="UX benchmark workspace.")
    parser.add_argument("--dir", default="benchmark", help="workspace root; default ./benchmark")
    subs = parser.add_subparsers(dest="command", required=True)

    p = subs.add_parser("init"); p.set_defaults(func=cmd_init)
    p.add_argument("--flow", required=True); p.add_argument("--steps", required=True)
    p.add_argument("--competitors", required=True); p.add_argument("--force", action="store_true")

    p = subs.add_parser("add"); p.set_defaults(func=cmd_add)
    p.add_argument("--competitor", required=True); p.add_argument("--step", required=True)
    p.add_argument("--file", required=True); p.add_argument("--source", default="")
    p.add_argument("--at", default=""); p.add_argument("--note", default="")

    p = subs.add_parser("gap"); p.set_defaults(func=cmd_gap)
    p.add_argument("--competitor", required=True); p.add_argument("--step", required=True)
    p.add_argument("--cause", required=True, choices=GAP_CAUSES)
    p.add_argument("--note", default="")

    p = subs.add_parser("source"); p.set_defaults(func=cmd_source)
    p.add_argument("--competitor", required=True); p.add_argument("--id", required=True)
    p.add_argument("--kind", required=True, choices=("walkthrough", "spot", "mixed"))
    p.add_argument("--shows", required=True)

    p = subs.add_parser("status"); p.set_defaults(func=cmd_status)

    p = subs.add_parser("sheet"); p.set_defaults(func=cmd_sheet)
    p.add_argument("--step", default=""); p.add_argument("--all", action="store_true")

    args = parser.parse_args()
    if args.command == "sheet" and not args.all and not args.step:
        receipt(status="error", error_type="BadSpec", hint="Pass --step <name> or --all.")
        return 1
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
